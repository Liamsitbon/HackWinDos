#!/usr/bin/env python3
"""Bind direct Setup firmware to one explicit GPT partition UUID."""
import argparse
from pathlib import Path
import re
import sys
import uuid

ROOT = Path(__file__).resolve().parents[1]
RELATIVE = Path('Silicon/Apple/AppleSiliconPkg/Drivers/WindowsAutoBootDxe/J413DirectSetupTarget.h')


def render(identity):
    value = uuid.UUID(str(identity))
    if value.int == 0:
        raise ValueError('A zero target UUID is not bootable')
    fields = value.fields
    tail = value.bytes[8:]
    return ('/** Generated by tools/j413_direct_setup.py; explicit target, never auto-discovery. */\n'
            '#ifndef J413_DIRECT_SETUP_TARGET_H\n#define J413_DIRECT_SETUP_TARGET_H\n'
            '#define J413_DIRECT_SETUP_PARTUUID "'+str(value).upper()+'"\n'
            'STATIC CONST EFI_GUID mJ413DirectSetupGuid = {0x%08x, 0x%04x, 0x%04x, {%s}};\n' %
            (fields[0], fields[1], fields[2], ', '.join('0x%02x' % b for b in tail))+
            '#endif\n')


def target_uuid(root=ROOT):
    source = root/'platforms/j413/mu'/RELATIVE
    text = source.read_text()
    match = re.search(r'^#define J413_DIRECT_SETUP_PARTUUID "([0-9A-Fa-f-]+)"$', text, re.M)
    if match is None or text != render(match.group(1)):
        raise ValueError('Direct Setup target header is missing or inconsistent')
    return str(uuid.UUID(match.group(1))).upper()


def configure(identity, root=ROOT):
    text = render(identity)
    source, destination = root/'platforms/j413/mu'/RELATIVE, root/'mu'/RELATIVE
    old = source.read_text() if source.exists() else None
    if old is not None:
        target_uuid(root)
    if destination.exists() and destination.read_text() != old:
        raise ValueError('Mu target header has local edits; refusing to overwrite')
    source.parent.mkdir(parents=True, exist_ok=True)
    source.write_text(text)
    if destination.exists():
        destination.write_text(text)
    return target_uuid(root)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument('--partition-uuid')
    group.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        print(configure(args.partition_uuid) if args.partition_uuid else target_uuid())
    except (OSError, ValueError) as error:
        print('Direct Setup configuration stopped: '+str(error), file=sys.stderr)
        raise SystemExit(1)


if __name__ == '__main__':
    main()
